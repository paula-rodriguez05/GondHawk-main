# ---------------------------------------------------------------------------
# 1. Generador de datos simulados (para poder avanzar desde el día 1)
# ---------------------------------------------------------------------------

ZONES = ["gondola_A1", "gondola_A2", "gondola_A3", "pasillo_central", "gondola_B1"]
PRODUCTS = {
    "gondola_A1": "SKU_1001_snacks",
    "gondola_A2": "SKU_1002_bebidas",
    "gondola_A3": "SKU_1003_lacteos",
    "gondola_B1": "SKU_1004_aseo",
}


def generar_eventos_simulados(n_personas: int = 200, seed: int = 42) -> list[dict]:
    """Genera eventos de interacción simulados, con la MISMA forma que
    entregaría el pipeline real (módulo 6), para poder construir y probar
    el motor de recomendación sin esperar a los demás integrantes."""
    rng = random.Random(seed)
    eventos = []
    inicio = datetime(2026, 8, 20, 9, 0, 0)

    for _ in range(n_personas):
        track_id = str(uuid.uuid4())  # id anónimo, no reversible a persona
        zona = rng.choice(ZONES)
        t = inicio + timedelta(seconds=rng.randint(0, 8 * 3600))

        # Toda persona "pasa" o se "acerca"
        if rng.random() < 0.55:
            eventos.append(_evento(track_id, zona, "pass_by", 0, t))
            continue

        dwell = round(rng.uniform(2, 45), 1)
        eventos.append(_evento(track_id, zona, "approach", dwell, t))

        if rng.random() < 0.4:  # de los que se acercan, algunos toman producto
            eventos.append(_evento(track_id, zona, "pickup", dwell, t + timedelta(seconds=dwell)))
            if rng.random() < 0.35:  # y de esos, algunos lo devuelven
                eventos.append(
                    _evento(track_id, zona, "return", dwell, t + timedelta(seconds=dwell + 8))
                )

    return eventos


def _evento(track_id, zona, tipo, dwell, ts) -> dict:
    return {
        "track_id": track_id,
        "zone_id": zona,
        "product_id": PRODUCTS.get(zona, "SKU_desconocido"),
        "event_type": tipo,
        "dwell_time_s": dwell,
        "timestamp": ts.isoformat(),
    }


# ---------------------------------------------------------------------------
# 2. Cálculo de métricas por zona
# ---------------------------------------------------------------------------

@dataclass
class MetricasZona:
    zona: str
    producto: str
    pasos: int = 0
    acercamientos: int = 0
    tomas: int = 0
    devoluciones: int = 0
    dwell_total_s: float = 0.0

    @property
    def tasa_interaccion(self) -> float:
        total = self.pasos + self.acercamientos
        return round(self.acercamientos / total, 3) if total else 0.0

    @property
    def tasa_conversion(self) -> float:  # de los que se acercan, cuántos toman
        return round(self.tomas / self.acercamientos, 3) if self.acercamientos else 0.0

    @property
    def tasa_rechazo(self) -> float:  # de los que toman, cuántos devuelven
        return round(self.devoluciones / self.tomas, 3) if self.tomas else 0.0

    @property
    def dwell_promedio(self) -> float:
        return round(self.dwell_total_s / self.acercamientos, 1) if self.acercamientos else 0.0


def calcular_metricas(eventos: list[dict], forzar_validacion: bool = True) -> dict[str, MetricasZona]:
    """Calcula métricas por zona. Por defecto (forzar_validacion=True) los
    eventos pasan primero por el validador de privacidad/cumplimiento del
    Integrante 8: así el motor de recomendación nunca procesa un evento
    que no debía guardarse, y tampoco truena por datos incompletos o mal
    formados (esos eventos simplemente se descartan y se reportan)."""
    if forzar_validacion:
        eventos_validos, reporte = filtrar_eventos_validos(eventos)
        if reporte["eventos_no_conformes"] > 0:
            print(
                f"[privacy_compliance] Se descartaron {reporte['eventos_no_conformes']} "
                f"de {reporte['total_eventos']} eventos por no cumplir el esquema/privacidad."
            )
    else:
        eventos_validos = eventos

    metricas: dict[str, MetricasZona] = {}
    for e in eventos_validos:
        z = e["zone_id"]
        producto = e.get("product_id", "desconocido")
        if z not in metricas:
            metricas[z] = MetricasZona(zona=z, producto=producto)
        m = metricas[z]
        tipo = e.get("event_type")
        if tipo == "pass_by":
            m.pasos += 1
        elif tipo == "approach":
            m.acercamientos += 1
            m.dwell_total_s += e.get("dwell_time_s", 0.0)
        elif tipo == "pickup":
            m.tomas += 1
        elif tipo == "return":
            m.devoluciones += 1
    return metricas


# ---------------------------------------------------------------------------
# 3. Motor de reglas de recomendación
# ---------------------------------------------------------------------------

def generar_recomendaciones(metricas: dict[str, MetricasZona]) -> list[dict]:
    """Reglas simples y explicables (nada de caja negra) para sugerir
    cambios de ubicación o de producto. Pensado para que el equipo pueda
    ajustar los umbrales fácilmente en la etapa de pruebas (Etapa 7)."""
    recomendaciones = []

    for m in metricas.values():
        if m.tasa_interaccion < 0.15:
            recomendaciones.append({
                "zona": m.zona,
                "producto": m.producto,
                "tipo": "reubicar_a_zona_caliente",
                "motivo": f"Zona fría: solo {m.tasa_interaccion:.0%} de las personas que pasan se detienen.",
            })

        if m.tasa_conversion > 0 and m.tasa_rechazo > 0.4:
            recomendaciones.append({
                "zona": m.zona,
                "producto": m.producto,
                "tipo": "revisar_precio_o_empaque",
                "motivo": f"Alta tasa de devolución ({m.tasa_rechazo:.0%}): la gente toma el producto pero no se lo lleva.",
            })

        if m.dwell_promedio > 25 and m.tasa_conversion < 0.2:
            recomendaciones.append({
                "zona": m.zona,
                "producto": m.producto,
                "tipo": "mejorar_senalizacion_o_informacion",
                "motivo": f"La gente se detiene bastante ({m.dwell_promedio}s) pero pocos compran: puede faltar info o el producto no es claro.",
            })

        if m.tasa_interaccion > 0.5 and m.tasa_conversion > 0.5:
            recomendaciones.append({
                "zona": m.zona,
                "producto": m.producto,
                "tipo": "mantener_y_replicar",
                "motivo": "Zona caliente con buena conversión: usar como referencia para otras góndolas.",
            })

    return recomendaciones


