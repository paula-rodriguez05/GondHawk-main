PATRONES_SOSPECHOSOS = [
    re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"),          # correo
    re.compile(r"\b\d{7,10}\b"),                        # posible cédula/documento
    re.compile(r"\b\d{3}[-.\s]?\d{3}[-.\s]?\d{4}\b"),   # posible teléfono
]

EVENT_TYPES_VALIDOS = {"approach", "pickup", "return", "pass_by"}

# Catálogo cerrado de zonas, alineado con config/zonas.json del módulo 4
# (Arturo). Si el equipo agrega una zona nueva, se cambia en este único
# lugar — antes el validador aceptaba cualquier string alfanumérico,
# existiera o no la zona.
ZONAS_VALIDAS = {
    "gondola_A1", "gondola_A2", "gondola_A3", "pasillo_central", "gondola_B1",
}

FORMATOS_CAMPOS_PERMITIDOS = {
    "track_id": re.compile(r"^[0-9a-fA-F]{1,8}(-[0-9a-fA-F]{1,12}){0,4}$"),
    "product_id": re.compile(r"^SKU_[A-Za-z0-9_]+$"),
}


def _campo_tiene_formato_valido(campo: str, valor) -> bool:
    if campo == "event_type":
        return valor in EVENT_TYPES_VALIDOS

    if campo == "zone_id":
        # antes: solo regex de caracteres -> dejaba pasar zonas inexistentes
        return isinstance(valor, str) and valor in ZONAS_VALIDAS

    if campo == "dwell_time_s":
        return isinstance(valor, (int, float)) and not isinstance(valor, bool) and valor >= 0

    if campo == "timestamp":
        if not isinstance(valor, str):
            return False
        try:
            datetime.fromisoformat(valor)
            return True
        except ValueError:
            return False

    if campo == "bbox":
        # TODO: confirmar con el equipo si este campo realmente viaja hasta
        # acá. Los eventos reales que arma el módulo 6 no lo incluyen; si
        # nadie lo necesita, quitarlo de CAMPOS_PERMITIDOS reduce superficie
        # de riesgo innecesaria.
        return (
            isinstance(valor, (list, tuple))
            and len(valor) == 4
            and all(isinstance(v, (int, float)) for v in valor)
        )

    patron = FORMATOS_CAMPOS_PERMITIDOS.get(campo)
    if patron is not None:
        return isinstance(valor, str) and bool(patron.match(valor))

    return False


CAMPOS_PERMITIDOS = {
    "track_id", "zone_id", "product_id", "event_type",
    "dwell_time_s", "timestamp", "bbox",
}


def validar_registro(registro: dict) -> dict:
    """Revisa un único registro: nombre de campo, formato del valor y
    patrones sospechosos dentro del texto. Falla cerrado: si algo no se
    reconoce con certeza como válido, se marca como no conforme."""
    problemas = []

    for campo, valor in registro.items():
        campo_norm = campo.lower().strip()

        if campo_norm in CAMPOS_PROHIBIDOS:
            problemas.append(f"Campo prohibido presente: '{campo}'")
            continue

        if campo_norm not in CAMPOS_PERMITIDOS:
            problemas.append(f"Campo no reconocido en el esquema acordado: '{campo}'")
            continue

        if not _campo_tiene_formato_valido(campo_norm, valor):
            problemas.append(
                f"Campo '{campo}' no tiene el formato/tipo esperado (valor: {valor!r})"
            )

        if isinstance(valor, str):
            for patron in PATRONES_SOSPECHOSOS:
                if patron.search(valor):
                    problemas.append(
                        f"Valor de '{campo}' contiene un patrón identificable (correo/documento/teléfono)."
                    )
                    break

    return {
        "cumple": len(problemas) == 0,
        "problemas": problemas,
    }


def validar_lote(eventos: list[dict]) -> dict:
    """Revisa una lista de eventos y arma un reporte agregado."""
    reportes = [validar_registro(e) for e in eventos]
    total_no_cumplen = sum(1 for r in reportes if not r["cumple"])

    return {
        "total_eventos": len(eventos),
        "eventos_no_conformes": total_no_cumplen,
        "cumple_todo_el_lote": total_no_cumplen == 0,
        "detalle_no_conformes": [
            {"indice": i, **r} for i, r in enumerate(reportes) if not r["cumple"]
        ],
    }


def filtrar_eventos_validos(eventos: list[dict]) -> tuple[list[dict], dict]:
    """Punto de entrada obligatorio hacia el resto del pipeline (módulo 6
    y el motor de recomendación): separa los eventos que cumplen de los
    que no, para que SOLO los conformes puedan seguir de largo.

    Devuelve (eventos_validos, reporte_completo).
    """
    reporte = validar_lote(eventos)
    indices_malos = {d["indice"] for d in reporte["detalle_no_conformes"]}
    eventos_validos = [e for i, e in enumerate(eventos) if i not in indices_malos]
    return eventos_validos, reporte


